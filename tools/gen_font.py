#!/usr/bin/env python3
"""Pack engine/font/console5x7.txt into a const C++ table.

The art file is one 5x7 picture per character (see its own header for the
format). This turns it into pse_font.hpp: a 128 entry lookup from character to
glyph, and seven bytes of rows per glyph, both `constexpr` so they live in
flash and cost no RAM.

Run by CMake into the build directory. Generated files are never committed,
same rule the .obj model pipeline follows.

    gen_font.py --art engine/font/console5x7.txt --out <build dir>
"""

import argparse
import os
import sys

GLYPH_W = 5
GLYPH_H = 7

HEADER_NOTE = ("// Generated by tools/gen_font.py from engine/font/console5x7.txt.\n"
               "// Do not edit: edit the picture and rebuild.\n\n")


def fail(msg):
    sys.stderr.write("gen_font: error: %s\n" % msg)
    sys.exit(1)


def parse(path):
    """Art file -> {character: [7 row bitmaps]}.

    A row bitmap has the leftmost ink pixel in bit 4, so a row draws by
    shifting right and testing bit 0 after masking.
    """
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")

    glyphs = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.startswith("@"):
            # Outside a glyph, blanks and '#' lines are commentary.
            if line.strip() and not line.lstrip().startswith("#"):
                fail("%s:%d: expected a glyph header '@X' or a comment, got %r"
                     % (os.path.basename(path), i, line))
            continue

        # A bare '@' is the space glyph. Writing it as '@' plus a literal space
        # would work until the first editor that strips trailing whitespace.
        ch = " " if len(line) == 1 else line[1]
        if len(line) > 2:
            fail("%s:%d: a glyph header is '@' and one character, got %r"
                 % (os.path.basename(path), i, line))
        if ord(ch) > 126 or ord(ch) < 32:
            fail("%s:%d: character %r is outside printable ASCII"
                 % (os.path.basename(path), i, ch))
        if ch in glyphs:
            fail("%s:%d: character %r is drawn twice"
                 % (os.path.basename(path), i, ch))

        rows = []
        for r in range(GLYPH_H):
            if i >= len(lines):
                fail("%s: glyph %r ends the file after %d of %d rows"
                     % (os.path.basename(path), ch, r, GLYPH_H))
            art = lines[i]
            i += 1
            if len(art) != GLYPH_W:
                fail("%s:%d: glyph %r row %d is %d characters wide, every row "
                     "is exactly %d" % (os.path.basename(path), i, ch, r + 1,
                                        len(art), GLYPH_W))
            bits = 0
            for x, cell in enumerate(art):
                if cell == "#":
                    bits |= 1 << (GLYPH_W - 1 - x)
            rows.append(bits)
        glyphs[ch] = rows

    if not glyphs:
        fail("%s holds no glyphs" % os.path.basename(path))
    if " " not in glyphs:
        fail("%s has no space glyph. Every name the menu draws has spaces in "
             "it." % os.path.basename(path))
    return glyphs


def emit(glyphs):
    ordered = sorted(glyphs)
    slot = {ch: n for n, ch in enumerate(ordered)}

    # 0 means "this character has no picture". Slots are stored plus one so the
    # sentinel needs no separate table.
    index = [0] * 128
    for ch, n in slot.items():
        index[ord(ch)] = n + 1

    out = [HEADER_NOTE,
           "#pragma once\n\n#include <cstdint>\n\nnamespace pse {\nnamespace font {\n\n",
           "constexpr int k_glyph_count = %d;\n\n" % len(ordered),
           "// Character code -> glyph slot plus one. 0 is a character the font\n"
           "// does not carry, which draws as a blank and never as a wrong glyph.\n",
           "constexpr uint8_t k_index[128] = {\n"]
    for row_start in range(0, 128, 16):
        row = ", ".join("%d" % v for v in index[row_start:row_start + 16])
        out.append("    %s,\n" % row)
    out.append("};\n\n")

    out.append("// Seven rows a glyph, leftmost ink pixel in bit %d.\n" % (GLYPH_W - 1))
    out.append("constexpr uint8_t k_rows[k_glyph_count][%d] = {\n" % GLYPH_H)
    for ch in ordered:
        rows = ", ".join("0x%02X" % v for v in glyphs[ch])
        label = "space" if ch == " " else repr(ch)
        out.append("    {%s},  // %s\n" % (rows, label))
    out.append("};\n\n}  // namespace font\n}  // namespace pse\n")
    return "".join(out)


def write_if_changed(path, content):
    """Do not touch the file when the bytes match, so nothing rebuilds."""
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            if f.read() == content:
                return
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--art", required=True, help="the 5x7 picture file")
    ap.add_argument("--out", required=True, help="directory for pse_font.hpp")
    args = ap.parse_args(argv)

    glyphs = parse(args.art)
    write_if_changed(os.path.join(args.out, "pse_font.hpp"), emit(glyphs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
