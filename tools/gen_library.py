#!/usr/bin/env python3
"""Generate the console's menu from console.yaml.

The console is one binary holding every game it lists, and this is what turns
the list into code: console_library.cpp, a const table of
{name, slug, &pse_game_<slug>, icon} that console/src/menu.cpp draws and
console/src/main.cpp dispatches through. Also console_games.cmake, so the
build compiles exactly the games the menu will show and no others.

Modelled on PicoCrystal-GBC's tools/gen_rom_data.py, including the part that
matters most: it refuses. A slug with no game, a name the font cannot draw, a
title too wide for the header, a game listed twice, a game that is not a
32blit game, a menu with nothing in it. Every one of those is a console that
boots into something wrong, and none of them is visible by looking at the
device.

A row's name is the one thing that used to be refused and is not: the menu
slides a name too wide for its row while that row is selected, so a long name
is a thing to look at rather than a thing to rename. The width is still
measured here, only to say in the build log which names will do it.

    gen_library.py --config console.yaml --games games --out <build dir>
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import game_meta  # noqa: E402  (needs the path above)
import gen_font  # noqa: E402

# Must match console/src/library.hpp.
ICON_PX = 24

# Must match console/src/menu.hpp, which publishes both numbers and
# static_asserts them against the layout menu.cpp draws. A name wider than
# NAME_ROOM_PX is fine: the menu scrolls it. A title wider than TITLE_ROOM_PX
# is not, because the header does not scroll and the battery icon is sitting
# in the space it would want.
NAME_ROOM_PX = 177
TITLE_ROOM_PX = 202
NAME_SCALE = 2
GLYPH_ADVANCE = 6

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_ART = os.path.join(REPO_ROOT, "engine", "font", "console5x7.txt")

HEADER_NOTE = ("// Generated by tools/gen_library.py from console.yaml.\n"
               "// Do not edit: edit the list and rebuild.\n\n")


class LibraryError(Exception):
    """Raised when the list cannot become a console."""


def symbol(slug):
    """Slug -> the C symbol a game exports.

    Hyphens become underscores, because `pico-santa` is a directory name and
    `pse_game_pico_santa` is an identifier. PSE_GAME() in the game does the
    same substitution by hand, so the two have to agree: see pse/game.hpp.
    """
    return slug.replace("-", "_")


def name_width(text, scale=NAME_SCALE):
    """Pixels a name takes, the same sum pse::text_width() does."""
    if not text:
        return 0
    return (len(text) * GLYPH_ADVANCE - 1) * scale


def display_name(title):
    """game.yml title -> a menu name, in the font's charset.

    Upper cased, and anything the font has no picture for becomes a space, the
    same normalisation PicoCrystal's display_name() does for the same reason:
    the menu draws with one small font and a name is not the place to find out
    it has no lower case.
    """
    out = []
    for char in title.upper():
        out.append(char)
    return " ".join("".join(out).split())


# ---- the config ----

def read_yaml_ish(path):
    """Read console.yaml without a yaml dependency.

    The rest of this repo's tooling parses its own yaml for the same reason:
    the build runs on a bare runner and a pip install for six keys is a
    dependency that has to keep working. This handles exactly the shape
    console.yaml is documented to have: `key: value` at the top level, and a
    `menu:` list of `- key: value` items with optional continuation keys.
    """
    if not os.path.isfile(path):
        raise LibraryError("no console.yaml at %s. The console's menu is a "
                           "decision written down, not one inferred from what "
                           "happens to be in games/." % path)

    top = {}
    menu = []
    in_menu = False
    current = None

    with open(path, "r", encoding="utf-8") as handle:
        for lineno, raw in enumerate(handle, 1):
            line = raw.split("#", 1)[0].rstrip()
            if not line.strip():
                continue

            stripped = line.strip()
            indent = len(line) - len(line.lstrip())

            if indent == 0 and not stripped.startswith("-"):
                key, _, value = stripped.partition(":")
                key = key.strip()
                value = value.strip().strip('"').strip("'")
                if key == "menu":
                    in_menu = True
                    current = None
                    continue
                in_menu = False
                top[key] = value
                continue

            if not in_menu:
                raise LibraryError("console.yaml:%d: %r is not at the top "
                                   "level and not under menu:" % (lineno, stripped))

            if stripped.startswith("-"):
                stripped = stripped[1:].strip()
                current = {"line": lineno}
                menu.append(current)

            if current is None:
                raise LibraryError("console.yaml:%d: %r comes before any menu "
                                   "entry" % (lineno, stripped))

            key, sep, value = stripped.partition(":")
            if not sep:
                raise LibraryError("console.yaml:%d: %r is not 'key: value'"
                                   % (lineno, stripped))
            current[key.strip()] = value.strip().strip('"').strip("'")

    return top, menu


def read_game_yml(path):
    """The handful of game.yml fields the console cares about."""
    fields = {}
    with open(path, "r", encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("#", 1)[0].rstrip()
            if not line or line[0].isspace() or ":" not in line:
                continue
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip().strip('"').strip("'")
    return fields


# ---- building the catalog ----

def build_catalog(config_path, games_dir):
    top, menu = read_yaml_ish(config_path)

    title = display_name(top.get("title", "PICO CONSOLE"))
    charset = set(gen_font.parse(FONT_ART))

    def check_drawable(text, where):
        missing = sorted({c for c in text if c not in charset})
        if missing:
            raise LibraryError(
                "%s: the console's font has no picture for %s. Its charset is "
                "the pictures in engine/font/console5x7.txt; add a glyph there "
                "or rename the entry." % (where, ", ".join(repr(c) for c in missing)))

    check_drawable(title, "console.yaml title")
    if name_width(title) > TITLE_ROOM_PX:
        raise LibraryError("console.yaml title %r is %d pixels wide and the "
                           "header has room for %d, the rest being the battery"
                           % (title, name_width(title), TITLE_ROOM_PX))

    entries = []
    seen = set()
    for item in menu:
        where = "console.yaml:%d" % item["line"]

        if "heading" in item:
            heading = display_name(item["heading"])
            check_drawable(heading, where)
            entries.append({"name": heading, "slug": "", "game": None,
                            "icon": None})
            continue

        if "game" not in item:
            raise LibraryError("%s: a menu entry is either 'game: <slug>' or "
                               "'heading: <text>'" % where)

        slug = item["game"]
        if slug in seen:
            raise LibraryError("%s: %s is listed twice. Two rows running the "
                               "same game share its save and its records."
                               % (where, slug))
        seen.add(slug)

        game_dir = os.path.join(games_dir, slug)
        yml = os.path.join(game_dir, "game.yml")
        if not os.path.isfile(yml):
            available = sorted(d for d in os.listdir(games_dir)
                               if os.path.isfile(os.path.join(games_dir, d,
                                                              "game.yml")))
            raise LibraryError("%s: no game called %r. games/ holds: %s"
                               % (where, slug, ", ".join(available)))

        fields = read_game_yml(yml)
        sdk = fields.get("sdk", "32blit")
        if sdk != "32blit":
            raise LibraryError("%s: %s builds against %r. The console links "
                               "every game into one binary, which only works "
                               "for games built against the one SDK this repo "
                               "uses (rule 6)." % (where, slug, sdk))

        name = display_name(item.get("name") or fields.get("title") or slug)
        check_drawable(name, where)

        icon_rows, icon_source = game_meta.icon_for(game_dir, slug, ICON_PX)
        entries.append({"name": name, "slug": slug, "game": slug,
                        "icon": icon_rows, "icon_source": icon_source})

    playable = [e for e in entries if e["game"]]
    if not playable:
        raise LibraryError("console.yaml lists no games, so the console would "
                           "boot to an empty menu.")

    return title, entries, [e["slug"] for e in playable]


# ---- output ----

def emit_library(title, entries):
    out = [HEADER_NOTE,
           '#include "library.hpp"\n\n',
           "namespace console {\n\n"]

    for index, entry in enumerate(entries):
        if entry["icon"] is None:
            continue
        out.append("// %s, from %s\n" % (entry["slug"], entry["icon_source"]))
        out.append("static const uint16_t k_icon_%d[%d] = {\n"
                   % (index, ICON_PX * ICON_PX))
        for row in entry["icon"]:
            packed = ", ".join(
                "0x%04X" % (((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
                for r, g, b in row)
            out.append("    %s,\n" % packed)
        out.append("};\n\n")

    for entry in entries:
        if entry["game"]:
            out.append("PSE_GAME_DECL(%s);\n" % symbol(entry["game"]))
    out.append("\n")

    out.append("const Entry k_library[] = {\n")
    for index, entry in enumerate(entries):
        game = ("&pse_game_%s" % symbol(entry["game"])
                if entry["game"] else "nullptr")
        icon = "k_icon_%d" % index if entry["icon"] is not None else "nullptr"
        out.append('    {"%s", "%s", %s, %s},\n'
                   % (entry["name"], entry["slug"], game, icon))
    out.append("};\n\n")
    out.append("const int k_library_count = %d;\n\n" % len(entries))
    out.append('const char* const k_console_title = "%s";\n\n' % title)
    out.append("}  // namespace console\n")
    return "".join(out)


def emit_stubs(slugs):
    """A do nothing pse::Game per slug, for the host harnesses.

    The menu preview and the layout tests draw the real generated library,
    with the real names and the real icons, but they have no business
    compiling four games and the 3D engine to do it. These satisfy the table's
    references and nothing else. Only console/tests links this.
    """
    out = [HEADER_NOTE,
           '#include "pse/game.hpp"\n\n',
           "namespace {\n"
           "void nothing() {}\n"
           "void nothing_timed(uint32_t) {}\n"
           "}  // namespace\n\n"]
    for slug in slugs:
        out.append("PSE_GAME(%s, nothing, nothing_timed, nothing_timed);\n"
                   % symbol(slug))
    return "".join(out)


def emit_cmake(slugs):
    return ("# Generated by tools/gen_library.py from console.yaml.\n"
            "# The games the console build compiles, and nothing else: the\n"
            "# menu and the binary are made from one list.\n"
            "set(CONSOLE_GAMES %s)\n" % " ".join(slugs))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=os.path.join(REPO_ROOT, "console.yaml"))
    ap.add_argument("--games", default=os.path.join(REPO_ROOT, "games"))
    ap.add_argument("--out", required=True, help="directory to write into")
    args = ap.parse_args(argv)

    try:
        title, entries, slugs = build_catalog(args.config, args.games)
    except LibraryError as error:
        sys.stderr.write("gen_library: error: %s\n" % error)
        return 1

    gen_font.write_if_changed(os.path.join(args.out, "console_library.cpp"),
                              emit_library(title, entries))
    gen_font.write_if_changed(os.path.join(args.out, "console_games.cmake"),
                              emit_cmake(slugs))
    gen_font.write_if_changed(os.path.join(args.out, "console_game_stubs.cpp"),
                              emit_stubs(slugs))

    # Which names the menu will slide, named rather than counted: it is not an
    # error, but it is worth knowing before flashing that a row does not sit
    # still.
    scrolling = [e["name"] for e in entries
                 if e["game"] and name_width(e["name"]) > NAME_ROOM_PX]
    sys.stderr.write("gen_library: %d games, %d rows\n"
                     % (len(slugs), len(entries)))
    for name in scrolling:
        sys.stderr.write("gen_library: %r is %d pixels wide of the %d a row "
                         "has, so the menu scrolls it\n"
                         % (name, name_width(name), NAME_ROOM_PX))
    return 0


if __name__ == "__main__":
    sys.exit(main())
