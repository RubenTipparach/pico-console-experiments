#!/usr/bin/env python3
"""Turn a PNG into a const table in flash: a `pse::Texture` or a `pse::Sprite`.

The mirror of obj2cpp.py for pictures. A texture stays a real PNG that opens in
any image editor, and this converts it at configure time into a const table the
build compiles. Nothing generated is ever committed, same rule as the models.

Power of two only, and that is the rasterizer's requirement rather than this
tool's: sampling is a shift and a mask, so wrapping is free and there is no
divide anywhere near the inner loop. A non power of two would need a modulo per
pixel on a core with no divide instruction.

The decoder is game_meta.py's, which is hand written and dependency free on
purpose: this repo builds from a bare checkout with nothing installed, and
adding Pillow to the critical path of every CI run to read a 32 by 32 image
would be a poor trade.

Two shapes come out of here, because the engine has two things a picture can
be and they have opposite requirements.

  --kind texture  a `pse::Texture` for the 3D rasterizer. Power of two, three
                  bytes a texel, no alpha, because sampling is a shift and a
                  mask and wrapping has to be free.
  --kind sprite   a `pse::Sprite` for the 2D blitter. Any size, four bytes a
                  pixel, and alpha is a mask: a texel is either drawn or it is
                  not. Sheets are ordinary sprites; the caller names the cell.

Usage:
  png2cpp.py wall.png --out-cpp wall.cpp --out-hpp wall.hpp
             --name wall --namespace tomlander
  png2cpp.py coins.png --kind sprite --out-cpp coins.cpp --out-hpp coins.hpp
             --name coins --namespace catcoin
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from game_meta import read_png       # noqa: E402


class TextureError(Exception):
    pass


def power_of_two_shift(value, what):
    shift = value.bit_length() - 1
    if value <= 0 or (1 << shift) != value:
        raise TextureError(
            "%s is %d, which is not a power of two. The rasterizer samples "
            "with a shift and a mask, so a texture has to be 8, 16, 32, 64 "
            "and so on." % (what, value))
    if shift > 8:
        raise TextureError(
            "%s is %d. A texture coordinate is carried as one byte, so past "
            "256 the extra texels are unreachable." % (what, value))
    return shift


def emit_header(name, namespace, kind):
    guard_ns = namespace.replace("-", "_")
    header = "pse/texture.hpp" if kind == "texture" else "pse/draw2d.hpp"
    struct = "pse::Texture" if kind == "texture" else "pse::Sprite"
    return (
        "// Generated by tools/png2cpp.py. Do not edit; edit the .png.\n"
        "#pragma once\n\n"
        "#include \"%s\"\n\n"
        "namespace models {\n"
        "namespace %s {\n\n"
        "extern const %s %s;\n\n"
        "}  // namespace %s\n"
        "}  // namespace models\n" % (header, guard_ns, struct, name, guard_ns))


def emit_sprite_source(name, namespace, width, height, rows, source_name):
    """A `pse::Sprite`: RGBA, row major, any size.

    No power of two check, because the blitter walks rows with a stride and
    never wraps: the constraint that makes a texture power of two is the
    shift-and-mask sample, and there is not one here.

    Fully transparent pixels are written as 0,0,0,0 rather than keeping
    whatever colour the editor left under them. Editors habitually store a
    colour behind a transparent pixel, and carrying it would make the diff of
    an art change depend on something nobody can see.
    """
    guard_ns = namespace.replace("-", "_")
    out = []
    out.append("// Generated by tools/png2cpp.py from %s.\n" % source_name)
    out.append("// %dx%d, four bytes a pixel, %d bytes of flash.\n"
               % (width, height, width * height * 4))
    out.append("#include \"%s/%s.hpp\"\n\n" % (guard_ns, name))
    out.append("namespace models {\n")
    out.append("namespace %s {\n" % guard_ns)
    out.append("namespace {\n\n")
    out.append("const uint8_t k_pixels[] = {\n")
    for y in range(height):
        row = []
        for x in range(width):
            r, g, b, a = rows[y][x]
            if a < 128:
                row.append("0,0,0,0,")
            else:
                row.append("%d,%d,%d,%d," % (r, g, b, a))
        out.append("    " + " ".join(row) + "\n")
    out.append("};\n\n")
    out.append("}  // namespace\n\n")
    out.append("const pse::Sprite %s = {k_pixels, %d, %d};\n\n"
               % (name, width, height))
    out.append("}  // namespace %s\n" % guard_ns)
    out.append("}  // namespace models\n")
    return "".join(out)


def emit_source(name, namespace, width, height, rows, source_name):
    guard_ns = namespace.replace("-", "_")
    w_shift = power_of_two_shift(width, "width")
    h_shift = power_of_two_shift(height, "height")

    out = []
    out.append("// Generated by tools/png2cpp.py from %s.\n" % source_name)
    out.append("// %dx%d, three bytes a texel, %d bytes of flash.\n"
               % (width, height, width * height * 3))
    out.append("#include \"%s/%s.hpp\"\n\n" % (guard_ns, name))
    out.append("namespace models {\n")
    out.append("namespace %s {\n" % guard_ns)
    out.append("namespace {\n\n")
    out.append("const uint8_t k_texels[] = {\n")
    for y in range(height):
        row = []
        for x in range(width):
            r, g, b = rows[y][x][:3]
            row.append("%d,%d,%d," % (r, g, b))
        out.append("    " + " ".join(row) + "\n")
    out.append("};\n\n")
    out.append("}  // namespace\n\n")
    out.append("const pse::Texture %s = {k_texels, %d, %d};\n\n"
               % (name, w_shift, h_shift))
    out.append("}  // namespace %s\n" % guard_ns)
    out.append("}  // namespace models\n")
    return "".join(out)


def write_if_changed(path, text):
    """Same contract as obj2cpp's: rewrite only on a real change, but always
    touch, or the Makefiles generator re-runs this on every build forever."""
    existing = None
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as handle:
            existing = handle.read()
    if existing == text:
        os.utime(path, None)
        return False
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    return True


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("png")
    ap.add_argument("--out-cpp", required=True)
    ap.add_argument("--out-hpp", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--namespace", required=True)
    ap.add_argument("--kind", choices=("texture", "sprite"), default="texture")
    args = ap.parse_args(argv[1:])

    sprite = args.kind == "sprite"
    width, height, rows = read_png(args.png, keep_alpha=sprite)
    source_name = os.path.basename(args.png)

    try:
        if sprite:
            cpp = emit_sprite_source(args.name, args.namespace, width, height,
                                     rows, source_name)
        else:
            cpp = emit_source(args.name, args.namespace, width, height, rows,
                              source_name)
    except TextureError as error:
        sys.stderr.write("png2cpp: %s: %s\n" % (args.png, error))
        return 1

    write_if_changed(args.out_hpp,
                     emit_header(args.name, args.namespace, args.kind))
    write_if_changed(args.out_cpp, cpp)
    print("png2cpp %s -> %s %dx%d, %d bytes of flash"
          % (source_name, args.kind, width, height,
             width * height * (4 if sprite else 3)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
